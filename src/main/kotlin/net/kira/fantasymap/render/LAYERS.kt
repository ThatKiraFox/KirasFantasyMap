package net.kira.fantasymap.render

//enum class слоев карты. Чем раньше декларирован слой - тем ниже он в приоритете (АКА. другие рисуются поверх него)
enum class LAYERS {
    HEIGHT, //Карта высот
    MOISTURE, //Карта влажности. Покрывает всю карту и перекрывает тем самым все, что раньше
    BIOMES, //Карта биомов. Покрывает всю карту и перекрывает тем самым все, что раньше
    LAKES, //Озера. Рисуются поверх
    RIVERS, //Реки. Рисуются поверх
    CELLS, //Границы ячеек. Outline ячеек становится черным, чтобы можно было легко их увидеть

}